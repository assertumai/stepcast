/**
 * Объявление экрана — общий модуль двух половин (`ui-screens`, design.md
 * Решение 9, 14).
 *
 * Модуль не несёт ни одного импорта нарочно: серверная половина читает его
 * обычным относительным путём, браузерная — тем же путём из `ui/`, собранная
 * Vite без единого типа Node (`ui/tsconfig.json` не подключает `@types/node`).
 * Любая зависимость здесь — что серверная, что браузерная — сделала бы
 * `npm run typecheck:ui` заложником модулей, которых у витрины нет.
 */

/** Место экрана в навигации. Отсутствует у экрана без пункта меню. */
export interface ScreenNav {
  /** Порядок пункта: меньшее значение — выше. */
  readonly order: number;
}

/**
 * Объявление экрана: `id`, заголовок, место в навигации и параметры, которые
 * он принимает. Путь по умолчанию — поле `path`, названо временным
 * (`ui-screens`, «Объявление экрана называет id и параметры, а не адрес»):
 * сегодня его назначает поставка, до `user-defined-routes` — пользователь.
 *
 * `path` — шаблон адреса: сегменты вида `:имя` — обязательный параметр,
 * `:имя?` — необязательный (допустим только последним сегментом). `params`
 * называет имена параметров в объявленном экраном порядке — тем же, в каком
 * они появляются в `path`.
 */
export interface ScreenDeclaration {
  readonly id: string;
  readonly title: string;
  readonly nav?: ScreenNav;
  readonly params: readonly string[];
  readonly path: string;
  /**
   * Закрытые перечни значений параметров — по имени параметра. Сегмент, не
   * попавший в перечень, шаблону не подходит вовсе, и адрес разбирается так
   * же, как любой другой неизвестный: экраном по умолчанию (`ui-screens`,
   * «Переведённые экраны не меняют поведения» — до перевода `/usage/вчера`
   * вёл на экран прогонов, а не открывал расход за подставленный период).
   *
   * Объявляет его сам экран, а не маршрутизатор: перечень пресетов периода —
   * дело экрана расхода, и `src/ui/routes.ts` знает только форму записи.
   * Параметр без перечня принимает любой безопасный сегмент, как и раньше.
   */
  readonly paramValues?: Readonly<Record<string, readonly string[]>>;
}

/**
 * Объявление экрана в ответе `GET /api/screens` — то же самое плюс признак
 * происхождения строки (`ui-screens`, «Экран отключается и заменяется патчем
 * состава»).
 *
 * `builtin: false` означает, что объявление принесла не строка поставки
 * витрины, а чужой модуль: его браузерную половину страница взять негде — в
 * бандле её нет, а чтение половин с диска — работа `user-plugins-from-files`.
 * Без этого признака страница применила бы к заменённому экрану встроенную
 * половину: `id` у замены тот же самый (design.md, Решение 13).
 */
export interface ScreenListing extends ScreenDeclaration {
  readonly builtin: boolean;
}

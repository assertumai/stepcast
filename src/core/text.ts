/**
 * Обезвреживание чужого свободного текста перед тем, как он попадёт в
 * однострочную запись — ленту хода прогона или журнал событий.
 *
 * Общее место для правила: управляющие последовательности сняты, переводы
 * строк заменены пробелами, длинный хвост обрезан. Раскраска вывода команды
 * предиката или многострочная деталь отказа иначе прошли бы насквозь.
 */

/**
 * Предел свободного текста в одной строке.
 *
 * Деталь события — чужой текст произвольной длины: вывод команды предиката
 * (`core/expect/evaluate.ts`), сообщение отказа бэкенда, вход отклонённого
 * вызова инструмента. Целиком они принадлежат журналу и файлам шага, строка
 * даёт начало.
 */
const DETAIL_LIMIT = 200;

const ESC = String.fromCharCode(0x1b);
const BEL = String.fromCharCode(0x07);

/** OSC (заголовок окна, ссылки): своя терминация — BEL либо ST. */
const OSC = new RegExp(`${ESC}\\][\\s\\S]*?(?:${BEL}|${ESC}\\\\)`, 'g');
/** CSI: раскраска, перемещение курсора, очистка строки. */
const CSI = new RegExp(`${ESC}\\[[0-9;:?]*[ -/]*[@-~]`, 'g');
/** Однобуквенные escape-последовательности вроде `ESC c`. */
const SHORT_ESCAPE = new RegExp(`${ESC}[@-_]`, 'g');
/**
 * Управляющие символы: перевод строки, возврат каретки, табуляция и остатки
 * оборванных последовательностей. `\p{Cc}` вместо диапазона с управляющими
 * символами в самом литерале — их в исходнике быть не должно.
 */
const CONTROL = /\p{Cc}+/gu;

/**
 * Чужой текст в одну строку: без управляющих последовательностей и переводов
 * строк, с обрезкой по `DETAIL_LIMIT`.
 */
export function inline(text: string): string {
  const flattened = text
    .replace(OSC, '')
    .replace(CSI, '')
    .replace(SHORT_ESCAPE, '')
    .replace(CONTROL, ' ')
    .replace(/\s+/g, ' ')
    .trim();
  return flattened.length <= DETAIL_LIMIT ? flattened : `${flattened.slice(0, DETAIL_LIMIT)}…`;
}

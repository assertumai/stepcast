/**
 * Якорь состояния рабочего дерева.
 *
 * Одна запись, закрывающая четыре разных вопроса: от чего восстанавливать
 * дерево при возобновлении, относительно чего считать «изменилось», из чего
 * выводить `diff.patch`, что сравнивать между прогонами. Без неё каждая из
 * четырёх возможностей завела бы собственное представление о состоянии дерева.
 *
 * Снятие якоря — внутренний учёт движка: его неудача проходит через
 * `run/bookkeeping.ts` и статусов не касается.
 */

/**
 * Способ фиксации. Якоря разных способов несравнимы, а не различаются.
 *
 * `composite` — корень плюс объявленные вложенные репозитории (`project.
 * nested_repos`), каждый снят собственным `git`-якорем; сам способ выбирается
 * один раз на прогон, как `git` и `manifest` (`detectAnchorKind`).
 */
export type AnchorKind = 'git' | 'manifest' | 'composite';

export interface Anchor {
  readonly kind: AnchorKind;
  /** Идентификатор состояния: объект дерева git или хеш манифеста. */
  readonly id: string;
}

/** Результат сравнения двух якорей. */
export type AnchorComparison =
  | { readonly comparable: true; readonly paths: readonly string[] }
  /**
   * Якоря сняты разными способами. Сравнивать их значения бессмысленно:
   * молчаливое сравнение несравнимого — ровно тот класс ошибок, из-за которого
   * кеши перестают вызывать доверие.
   */
  | { readonly comparable: false; readonly reason: string };

export interface TreeAnchorer {
  readonly kind: AnchorKind;

  /** Зафиксировать текущее состояние каталога. */
  capture(): Anchor;

  /**
   * Привести каталог к зафиксированному состоянию. Отказ не оставляет
   * частично применённого результата.
   */
  restore(anchor: Anchor): void;

  /**
   * Восстановить только перечисленные пути.
   *
   * Возобновление в каталоге запуска обязано пользоваться именно этим:
   * полный сброс дерева стёр бы файлы, которые пользователь создал после
   * прогона, — в том числе ту самую правку, ради которой он возобновляет.
   */
  restorePaths(anchor: Anchor, paths: readonly string[]): void;

  /** Пути, различающиеся между двумя состояниями. */
  changedPaths(from: Anchor, to: Anchor): AnchorComparison;

  /** Изменения между состояниями в виде патча, пригодного для наложения. */
  diff(from: Anchor, to: Anchor): string | undefined;

  /** Освободить временные ресурсы: индексный файл, промежуточные записи. */
  dispose(): void;
}

/**
 * Хранит ли якорь содержимое дерева, то есть можно ли привести к нему чужой
 * каталог. Хеш-манифест отвечает только на вопрос «изменилось ли», содержимого
 * файлов у него нет, и его `restore` объявленно отказывает
 * (`anchor/manifest.ts`). Составной якорь содержимое хранит, но по частям —
 * каждая в базе объектов своего вложенного репозитория: он восстанавливает
 * каталог, где каждая объявленная часть уже заведена рабочим деревом своего
 * репозитория, а на каталоге без частей отказывает той же причиной, что и
 * `git` на недоступных объектах (`anchor/composite.ts`). Условие проверяет
 * сам `restore` в момент вызова — здесь оно не перепроверяется, а лишь
 * называется допустимым как класс: наследование дерева обязано пробовать
 * составное состояние, а не обходить его молча.
 */
export function restorable(anchor: Anchor): boolean {
  return anchor.kind === 'git' || anchor.kind === 'composite';
}

export function sameAnchor(a: Anchor | undefined, b: Anchor | undefined): boolean {
  if (a === undefined || b === undefined) return false;
  return a.kind === b.kind && a.id === b.id;
}

import { StepcastError } from '../errors.js';
import { bookkeepAsync, type BookkeepingScope } from './bookkeeping.js';

/**
 * Область ресурсов: захват регистрирует обратную операцию, выход из области
 * исполняет зарегистрированные в обратном порядке.
 *
 * Раннер захватывает ресурсы в разных местах и на разной глубине — индексный
 * файл якоря, каталог черновиков, рабочее дерево с частями, слушатели отмены,
 * таймеры процесса. Порядок снятия для них не произволен: часть worktree
 * числится в каталоге корня, слушатель попытки ссылается на её контроллер.
 * Обратный порядок — единственный, при котором ни одна операция не находит
 * из-под себя уже убранное.
 *
 * Отказ обратной операции — учётная операция (см. `bookkeeping.ts`): он
 * пишется в журнал и на этом заканчивается. Снятие области не бросает наружу
 * и не подменяет причину, по которой область снимается: пользователь заказывал
 * результат работы, а не уборку за ней.
 */
export interface ResourceScope {
  /**
   * Зарегистрировать обратную операцию под именем, которым она будет названа
   * в журнале, если откажет. Регистрация идёт сразу после захвата: ресурс,
   * захваченный и не зарегистрированный, теряется при первом же отказе между
   * захватом и регистрацией.
   */
  defer(operation: string, dispose: () => void | Promise<void>): void;
  /** Исполнить зарегистрированные операции в обратном порядке регистрации. */
  dispose(): Promise<void>;
  /**
   * Отпустить область: очистить стек, ничего не исполняя. Нужно там, где
   * захваченное при успехе обязано пережить область, — рабочее дерево работы
   * снимается только `stepcast gc`, и снять его в конце прогона значило бы
   * нарушить объявленное требование.
   */
  release(): void;
}

/**
 * Область без журнала (`bookkeeping` не передан) предназначена только для
 * операций, которые не отказывают по устройству: `clearTimeout`,
 * `removeEventListener`. Сообщить об отказе такой операции некуда, и глотать
 * его нельзя — исключение выходит наружу, потому что означает дефект, а не
 * неудачу уборки.
 */
export function createScope(bookkeeping?: BookkeepingScope): ResourceScope {
  const stack: { readonly operation: string; readonly dispose: () => void | Promise<void> }[] = [];
  let disposed = false;

  return {
    defer(operation, dispose) {
      if (disposed) {
        // Молча потерять ресурс хуже, чем упасть: область снята, снимать его
        // больше некому, и утечка обнаружилась бы через прогон и через сутки.
        throw new StepcastError(
          `Регистрация обратной операции «${operation}» в уже снятой области ресурсов`,
          { hint: 'Это дефект движка: ресурс захвачен после снятия своей области' },
        );
      }
      stack.push({ operation, dispose });
    },

    async dispose() {
      // Идемпотентность нужна `finally`, который может сработать после явного
      // снятия: повторный вызов не имеет права исполнить операции дважды.
      disposed = true;
      while (stack.length > 0) {
        // Снятие со стека до вызова, а не после: операция, бросившая наружу в
        // области без журнала, не должна исполниться повторно.
        const entry = stack.pop() as { operation: string; dispose: () => void | Promise<void> };
        if (bookkeeping === undefined) {
          await entry.dispose();
          continue;
        }
        await bookkeepAsync(bookkeeping, entry.operation, async () => {
          await entry.dispose();
        });
      }
    },

    release() {
      disposed = true;
      stack.length = 0;
    },
  };
}

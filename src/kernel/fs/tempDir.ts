import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';

/**
 * Временный каталог движка: заводится, передаётся телу и снимается в
 * `finally` независимо от исхода, включая исключение, брошенное изнутри
 * `fn`. Владение остаётся у вызывающего — тело решает, что писать в каталог
 * и когда с ним закончило, а снятие происходит ровно тогда, когда `fn`
 * вернула управление или бросила.
 *
 * Исход вызова определяет тело, а не уборка: отказ снятия (занятый файл,
 * каталог, который держит переживший вызов процесс) называется путём в потоке
 * ошибок и не подменяет собой ни возвращённое значение, ни — что важнее —
 * исключение, ради которого `finally` и исполняется. Иначе пользователь вместо
 * «наложение не сошлось» получил бы ошибку файловой системы, а вызывающий,
 * толкующий любое исключение как отказ по существу (`canAdoptWorkspace`),
 * молча свернул бы работу из-за неубранного мусора.
 */
export function withTempDir<T>(prefix: string, fn: (dir: string) => T): T {
  const dir = mkdtempSync(join(tmpdir(), prefix));
  try {
    return fn(dir);
  } finally {
    try {
      rmSync(dir, { recursive: true, force: true });
    } catch (error) {
      process.stderr.write(`stepcast: не удалось снять временный каталог ${dir}: ${String(error)}\n`);
    }
  }
}
